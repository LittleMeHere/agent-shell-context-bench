"""Success-check executors.

A task YAML lists `success_checks`; ALL must pass for the trial to count as
a success (the binary primary outcome behind H1). Three families of check
exist, distinguished by what they read:

  * Snapshot-only — pure functions of the post-run FilesystemSnapshot:
    file_exists, directory_exists, file_is_empty, no_extra_files,
    no_files_matching.

  * Sandbox-content — read file bytes from the host filesystem. They need
    the sandbox host root, supplied via `evaluate_checks(...,
    sandbox_host_root=...)`. If it is not provided they fail closed:
    python_parses, file_contains_substring_count, file_content_equals,
    json_content_equals, file_count_matching.

  * Agent-trace — read the per-command stdout / stderr the agent issued
    during the trial. They need the agent's CommandRecord list, supplied
    via `evaluate_checks(..., agent_commands=...)`. If it is not provided
    they fail closed: agent_any_command_stdout_equals,
    agent_all_command_stderrs_empty.

Adding a new check type = add one function + one `@check("name")` + (if
the check needs context) one entry in `_CONTEXT_CHECKS` or
`_AGENT_CHECKS`. The runner calls `evaluate_checks` and never needs to
know the catalogue.

Path convention: all paths are sandbox-relative POSIX, matching
`FilesystemSnapshot`. A leading "./" in the YAML is tolerated and stripped.

Ignored artefacts: `__pycache__/` directories and `.pyc` / `.pyo` / `.pyd`
files are excluded from `no_extra_files` / `no_files_matching` /
`file_count_matching` and are never the target of a content check. They
are import-side-effect artefacts of any Python verification step (e.g.
an agent that runs `python -c "import lib"` to sanity-check its work).
Counting them as "extras" would penalise the more diligent agent — a
denominator-bias failure mode the pre-registration explicitly avoids.
"""

from __future__ import annotations

import ast
import fnmatch
import json
import re
from collections.abc import Callable, Mapping, Sequence
from pathlib import Path
from typing import Any

from .types import CheckResult, FilesystemSnapshot

CheckFn = Callable[[FilesystemSnapshot, Mapping[str, object]], CheckResult]

_REGISTRY: dict[str, CheckFn] = {}

# Python import-cache artefacts. Generated by ANY `python -c "import ..."`
# verification an agent may run; would otherwise spuriously fail
# no_extra_files / no_files_matching / file_count_matching. Listed here,
# not per-task, so the rule is uniform and auditable.
_IGNORE_DIR_NAMES: frozenset[str] = frozenset({
    "__pycache__",
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
})
_IGNORE_FILE_SUFFIXES: tuple[str, ...] = (".pyc", ".pyo", ".pyd")

# Check types that need to read file content from the host filesystem.
# evaluate_checks injects the sandbox host root into these specs.
_CONTEXT_CHECKS: frozenset[str] = frozenset({
    "python_parses",
    "file_contains_substring_count",
    "file_content_equals",
    "json_content_equals",
    "file_count_matching",
})

# Check types that need the agent's per-command transcript.
# evaluate_checks injects the agent_commands sequence into these specs.
_AGENT_CHECKS: frozenset[str] = frozenset({
    "agent_any_command_stdout_equals",
    "agent_all_command_stderrs_empty",
})


def _norm(path: object) -> str:
    p = str(path).replace("\\", "/").strip()
    return p[2:] if p.startswith("./") else p


def _is_ignored(rel_path: str) -> bool:
    """True if the path is a Python import-cache artefact (see module docstring)."""
    parts = rel_path.split("/")
    if any(part in _IGNORE_DIR_NAMES for part in parts):
        return True
    return rel_path.endswith(_IGNORE_FILE_SUFFIXES)


def _non_ignored_files(snap: FilesystemSnapshot) -> set[str]:
    return {p for p in snap.files if not _is_ignored(p)}


def check(name: str) -> Callable[[CheckFn], CheckFn]:
    def register(fn: CheckFn) -> CheckFn:
        _REGISTRY[name] = fn
        return fn

    return register


