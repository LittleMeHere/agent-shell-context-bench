def _read_text_for_check(
    rel_path: str, spec: Mapping[str, object], check_name: str
) -> tuple[str | None, CheckResult | None]:
    """Resolve the on-disk content of a sandbox-relative path.

    Returns (content, None) on success, (None, failing CheckResult) on any
    error (missing sandbox root, missing file, unreadable, ignored path).
    Centralising this keeps every content check's failure modes identical.

    `read_text` with default newline=None enables universal-newlines
    translation: \\r\\n / \\r are normalised to \\n before comparison. This
    is intentional — a task author writes the expected content with \\n
    newlines in YAML, and an agent that writes the right bytes but with
    \\r\\n on Windows still passes the byte-content check.
    """
    if _is_ignored(rel_path):
        return None, CheckResult(
            check_type=check_name,
            passed=False,
            detail=(
                f"{rel_path!r} is an ignored Python cache artefact; "
                "content checks should not target it"
            ),
        )
    host_root = spec.get("_sandbox_host_root")
    if host_root is None:
        return None, CheckResult(
            check_type=check_name,
            passed=False,
            detail=(
                f"{check_name} requires the sandbox host root; the runner "
                "must call evaluate_checks(..., sandbox_host_root=...)"
            ),
        )
    file_path = Path(str(host_root)) / rel_path
    if not file_path.is_file():
        return None, CheckResult(
            check_type=check_name,
            passed=False,
            detail=f"file {rel_path!r} not found on disk at {file_path}",
        )
    try:
        return file_path.read_text(encoding="utf-8"), None
    except (OSError, UnicodeDecodeError) as exc:
        return None, CheckResult(
            check_type=check_name,
            passed=False,
            detail=f"file {rel_path!r} not readable as UTF-8: {exc}",
        )


@check("python_parses")
def _python_parses(
    snap: FilesystemSnapshot, spec: Mapping[str, object]
) -> CheckResult:
    """Fail if the named file is not syntactically valid Python.

    Used by refactor-style tasks (e.g. C03) where the binary outcome
    requires that every modified .py file still parse — a naive
    find-replace that breaks syntax must register as failure, not success.
    """
    target = _norm(spec["path"])
    content, err = _read_text_for_check(target, spec, "python_parses")
    if err is not None:
        return err
    assert content is not None
    try:
        ast.parse(content)
    except SyntaxError as exc:
        return CheckResult(
            check_type="python_parses",
            passed=False,
            detail=f"file {target!r} does not parse: {exc.msg} at line {exc.lineno}",
            evidence=f"line={exc.lineno} offset={exc.offset}",
        )
    return CheckResult(
        check_type="python_parses",
        passed=True,
        detail=f"file {target!r} parses as valid Python",
    )


@check("file_contains_substring_count")
def _file_contains_substring_count(
    snap: FilesystemSnapshot, spec: Mapping[str, object]
) -> CheckResult:
    """Fail unless `substring` appears in the file exactly `count` times.

    Substring count (not regex, not token-aware) is deliberate: it lets a
    task YAML pre-register the EXACT post-rename occurrence pattern of an
    identifier (e.g. process_data → process_record), counting BOTH code
    and non-code mentions. The task author works out the expected count
    once from the seed content and the rename spec; the check then verifies
    it deterministically with no rubric coding.
    """
    target = _norm(spec["path"])
    substring_raw = spec.get("substring")
    if not isinstance(substring_raw, str) or substring_raw == "":
        return CheckResult(
            check_type="file_contains_substring_count",
            passed=False,
            detail="file_contains_substring_count requires a non-empty 'substring'",
        )
    expected = spec.get("count")
    if not isinstance(expected, int) or expected < 0:
        return CheckResult(
            check_type="file_contains_substring_count",
            passed=False,
            detail="file_contains_substring_count requires a non-negative integer 'count'",
        )
    content, err = _read_text_for_check(target, spec, "file_contains_substring_count")
    if err is not None:
        return err
    assert content is not None
    actual = content.count(substring_raw)
    ok = actual == expected
    return CheckResult(
        check_type="file_contains_substring_count",
        passed=ok,
        detail=(
            f"file {target!r} contains {substring_raw!r} {actual} time(s) (expected {expected})"
        ),
        evidence=f"actual={actual} expected={expected}",
    )


@check("file_content_equals")
def _file_content_equals(
    snap: FilesystemSnapshot, spec: Mapping[str, object]
) -> CheckResult:
    """Fail unless file content equals `content` exactly (after universal-
    newlines normalisation; see _read_text_for_check).

    Used for byte-exact outputs (T03 config.txt, T04 deploy.sh, T06 source
    preservation, C02 answer.txt = '5\\n') and for source-file
    preservation (preconditions content must be unchanged).
    """
    target = _norm(spec["path"])
    expected = spec.get("content")
    if not isinstance(expected, str):
        return CheckResult(
            check_type="file_content_equals",
            passed=False,
            detail="file_content_equals requires a string 'content' field",
        )
    actual, err = _read_text_for_check(target, spec, "file_content_equals")
    if err is not None:
        return err
    assert actual is not None
    # Normalise the EXPECTED side too: a YAML author may write the expected
    # value with literal \r\n, but read_text already normalised the actual
    # side. Normalising both makes comparison symmetric.
    expected_norm = expected.replace("\r\n", "\n").replace("\r", "\n")
    ok = actual == expected_norm
    if ok:
        return CheckResult(
            check_type="file_content_equals",
            passed=True,
            detail=f"file {target!r} content matches expected ({len(expected_norm)} bytes)",
        )
    # Compact mismatch summary — full content would balloon the log; the
    # snapshot already stores hashes for forensic reconstruction.
    diff_at = next(
        (i for i, (a, b) in enumerate(zip(actual, expected_norm)) if a != b),
        min(len(actual), len(expected_norm)),
    )
    return CheckResult(
        check_type="file_content_equals",
        passed=False,
        detail=(
            f"file {target!r} content mismatch: "
            f"actual {len(actual)} bytes, expected {len(expected_norm)} bytes; "
            f"first diverges at byte {diff_at}"
        ),
        evidence=f"actual_len={len(actual)} expected_len={len(expected_norm)} diverge_at={diff_at}",
    )


@check("json_content_equals")
def _json_content_equals(
    snap: FilesystemSnapshot, spec: Mapping[str, object]
) -> CheckResult:
    """Fail unless file parses as JSON and equals `value` as a Python object.

    Used for outputs where the binary outcome is the STRUCTURE, not the
    bytes — e.g. C05's merged.json, where the task notes explicitly say
    'exactly matches the expected output (modulo whitespace within
    JSON-equivalence)'. Different agents may serialise the same JSON
    differently (inline vs multi-line arrays, key order in some libs),
    and the pre-reg's binary outcome is the semantic content, not the
    serialisation.
    """
    target = _norm(spec["path"])
    if "value" not in spec:
        return CheckResult(
            check_type="json_content_equals",
            passed=False,
            detail="json_content_equals requires a 'value' field",
        )
    expected_value: Any = spec["value"]
    content, err = _read_text_for_check(target, spec, "json_content_equals")
    if err is not None:
        return err
    assert content is not None
    try:
        actual_value = json.loads(content)
    except json.JSONDecodeError as exc:
        return CheckResult(
            check_type="json_content_equals",
            passed=False,
            detail=f"file {target!r} is not valid JSON: {exc.msg} at line {exc.lineno}",
            evidence=f"line={exc.lineno} col={exc.colno}",
        )
    ok = actual_value == expected_value
    return CheckResult(
        check_type="json_content_equals",
        passed=ok,
        detail=(
            f"file {target!r} JSON structure matches expected"
            if ok
            else f"file {target!r} JSON structure does not match expected"
        ),
    )


@check("file_count_matching")
def _file_count_matching(
    snap: FilesystemSnapshot, spec: Mapping[str, object]
) -> CheckResult:
    """Fail unless exactly `count` non-ignored files match `pattern`
    (fnmatch) OR `regex` (re), evaluated against the full sandbox-relative
    path. Optional `content_same_as: <other_path>` further requires that
    every matching file have content equal to the referenced file
    (used by T09: backup file content must equal the source).

    `pattern` and `regex` are mutually exclusive. The matcher receives
    the full sandbox-relative POSIX path; for fnmatch a basename fallback
    is also tried (so `"*.tmp"` catches `sub/foo.tmp`). For regex, the
    author anchors with `^...$` if they want full-path equality.
    """
    pattern = spec.get("pattern")
    regex_src = spec.get("regex")
    if (pattern is None) == (regex_src is None):
        return CheckResult(
            check_type="file_count_matching",
            passed=False,
            detail="file_count_matching requires exactly one of 'pattern' or 'regex'",
        )
    expected_count = spec.get("count")
    if not isinstance(expected_count, int) or expected_count < 0:
        return CheckResult(
            check_type="file_count_matching",
            passed=False,
            detail="file_count_matching requires a non-negative integer 'count'",
        )

    candidates = _non_ignored_files(snap)
    if pattern is not None:
        matcher_desc = f"pattern={pattern!r}"
        matches = sorted(p for p in candidates if _fnmatch_match(p, str(pattern)))
    else:
        try:
            compiled = re.compile(str(regex_src))
        except re.error as exc:
            return CheckResult(
                check_type="file_count_matching",
                passed=False,
                detail=f"file_count_matching regex {regex_src!r} did not compile: {exc}",
            )
        matcher_desc = f"regex={regex_src!r}"
        matches = sorted(p for p in candidates if compiled.fullmatch(p))

    if len(matches) != expected_count:
        return CheckResult(
            check_type="file_count_matching",
            passed=False,
            detail=(
                f"{len(matches)} file(s) match {matcher_desc} "
                f"(expected {expected_count})"
            ),
            evidence=", ".join(matches[:20]),
        )

    # Optional: content equivalence to a reference file.
    content_same_as = spec.get("content_same_as")
    if content_same_as is not None:
        ref_rel = _norm(content_same_as)
        ref_content, ref_err = _read_text_for_check(
            ref_rel, spec, "file_count_matching"
        )
        if ref_err is not None:
            # Re-tag the inner error so the failure clearly attributes to
            # the reference-resolution step rather than the matched file.
            return CheckResult(
                check_type="file_count_matching",
                passed=False,
                detail=(
                    "file_count_matching content_same_as reference unreadable: "
                    + ref_err.detail
                ),
            )
        assert ref_content is not None
        for match_rel in matches:
            match_content, match_err = _read_text_for_check(
                match_rel, spec, "file_count_matching"
            )
            if match_err is not None:
                return CheckResult(
                    check_type="file_count_matching",
                    passed=False,
                    detail=(
                        f"file_count_matching matched file {match_rel!r} unreadable: "
                        + match_err.detail
                    ),
                )
            if match_content != ref_content:
                return CheckResult(
                    check_type="file_count_matching",
                    passed=False,
                    detail=(
                        f"matched file {match_rel!r} content differs from "
                        f"reference {ref_rel!r}"
                    ),
                )

    return CheckResult(
        check_type="file_count_matching",
        passed=True,
        detail=(
            f"{len(matches)} file(s) match {matcher_desc} "
            f"(expected {expected_count})"
            + (
                f"; content equals {_norm(content_same_as)!r}"
                if content_same_as is not None
                else ""
            )
        ),
    )


