def _expected_files_from(specs: Sequence[Mapping[str, object]]) -> set[str]:
    """Files a successful run must contain — i.e. every path asserted by an
    existence/content/parse/count check. Used to give no_extra_files its
    baseline so it means 'nothing the task did not ask for'."""
    out: set[str] = set()
    asserting_types = {
        "file_exists",
        "file_is_empty",
        "python_parses",
        "file_contains_substring_count",
        "file_content_equals",
        "json_content_equals",
    }
    for s in specs:
        if s.get("type") in asserting_types and "path" in s:
            out.add(_norm(s["path"]))
    return out


def evaluate_checks(
    snap: FilesystemSnapshot,
    specs: Sequence[Mapping[str, object]],
    *,
    sandbox_host_root: Path | str | None = None,
    agent_commands: Sequence[Any] | None = None,
) -> tuple[bool, list[CheckResult]]:
    """Run every check. Returns (overall_success, per-check results).

    overall_success is the AND of all checks — the trial's binary outcome.
    An unknown check type fails closed (returns a failing CheckResult rather
    than raising): a typo in a task YAML must not silently pass a trial.

    `sandbox_host_root` is the host-side path to the trial's sandbox. It is
    forwarded into content-based check specs (see _CONTEXT_CHECKS).
    `agent_commands` is the per-command transcript; it is forwarded into
    agent-trace check specs (see _AGENT_CHECKS). Snapshot-only checks
    ignore both.
    """
    expected = _expected_files_from(specs)
    results: list[CheckResult] = []
    for spec in specs:
        ctype = str(spec.get("type", ""))
        fn = _REGISTRY.get(ctype)
        if fn is None:
            results.append(
                CheckResult(
                    check_type=ctype or "<missing>",
                    passed=False,
                    detail=f"unknown check type {ctype!r} — fix the task YAML",
                )
            )
            continue
        if ctype == "no_extra_files":
            spec = {**spec, "_expected_files": tuple(expected)}
        elif ctype in _CONTEXT_CHECKS:
            spec = {**spec, "_sandbox_host_root": sandbox_host_root}
        elif ctype in _AGENT_CHECKS:
            spec = {**spec, "_agent_commands": agent_commands}
        results.append(fn(snap, spec))
    overall = all(r.passed for r in results)
    return overall, results
